import os
import torch
import torch.nn as nn
import torch.nn.functional as F

from deepSTRF.datasets.video.video_dataset import VideoNeuralDataset

class CRCNS_PVC1_Dataset(VideoNeuralDataset):
    """
    A PyTorch dataset for handling neural responses and video stimuli from the CRCNS PVC1 Dataset.

    =============== SOURCE ================

    See original papers for details:
      - "Precise alignment of micromachined electrode arrays with V1 functional maps" by Nauhaus et al. (2007)

    Data available at: https://crcns.org/data-sets/vc/pvc-1
    
    Key Publications:
    - Nauhaus et al., 2007. "Precise alignment of micromachined electrode arrays with V1 functional maps"
    - Ringach D., et al., (2002–2007), CRCNS.org PVC-1 Dataset, https://crcns.org/data-sets/vc/pvc-1

    =============== DETAILS ================

    - Neural responses were recorded from populations in primary visual cortex (V1) of Old-World monkeys 
      (Macaca fascicularis).
    - Visual stimuli consist of natural image sequences generated by digitally sampling commercially available
      VHS/NTSC videotapes.
    - Videos were sampled at 30 Hz (33.3 ms/frame) and presented on a 90 Hz display (each image shown 3 times).
    - Effective frame duration remains 33.3 ms from the perspective of the neural response.
    - Thirty 30-second segments were extracted from four different movies (e.g., Sleeper, Benji, Goldfinger, 
      Shakespeare in Love), yielding about 20 minutes of video.
    - Movie clips were compressed and presented at an effective refresh rate of 90 Hz (each image displayed for 
      three consecutive frames).

    =============== STRUCTURE ================

    The dataset is organized into several main attributes:
      - self.responses: Tensor of shape (N_neurons, N_seqs, Repeats, Time)
          Contains neural responses collected over multiple trials.
      - self.videos: Tensor of shape (N_seqs, Channels, Height, Width, Time)
          Contains video stimuli corresponding to the experimental conditions.
      - self.signal_powers: Precomputed signal power for each neuron and stimulus, useful for further analysis.

    Preprocessing options include:
      - Normalizing neural responses (with an option to smooth them using a Gaussian kernel).
      - Resizing video stimuli to a specified spatial resolution (default: 112×112 pixels) via interpolation.
      - Converting video frames from RGB to grayscale.
      - Optionally normalizing video intensities and adding random noise.

    Usage:
      Instantiate the dataset by providing the path and selecting the 'train' or 'test' split. The __getitem__ 
      method returns a tuple containing a video stimulus, its corresponding neural response, and the signal power 
      for the currently selected neuron.
      
    =============== WARNING NOTE ================
      
    - Each video corresponds to a (movie_id, segment_id) pair from the original dataset (4 movies × 30 segments). 
      This class does not preserve those identifiers explicitly but treats them as sequential video indices.

    """
    
    def __init__(self, 
                 path: str, 
                 set: str, 
                 spatial_resol: tuple=(112, 112), 
                 grayscale: bool=False,
                 normalize_videos: bool=False, 
                 normalize_responses: bool=True,
                 response_smoothing: bool=False,
                 add_noise: bool=False,
                 temporal_resolution: int=33,
                 split_into_clips : bool=False,
                 new_clip_len: int=3000):
      
        super().__init__(path)
        
        assert set == "train" or set == "test", f"Unexpected value '{set}' for argument 'set', choose between 'train' or 'test'."

        # load response data
        resps_path = os.path.join(path, f'multi_pvc1_{set}_1_ulysse.pt')
        stims_path = os.path.join(path, f'stims_multi_pvc1_{set}_1_ulysse.pt')

        self.responses = torch.load(resps_path, weights_only=False).permute(0, 1, 3, 2) # --> (N_neurons, N_seqs, R, T)
        self.videos = torch.load(stims_path, weights_only=False).permute(0, 1, 3, 4, 2) # --> (N_seqs, C=3, H, W, T)
        
        self.N_neurons, _, self.R, _ = self.responses.shape
        self.S, self.C, self.H, self.W, self.T = self.videos.shape
        
        self.native_temporal_resolution_video = 33.3  # ms per frame in videos
        self.native_temporal_resolution_responses = 33.3  # ms per sample in responses
        
        # Adapt temporal resolution to synchronize videos and responses.
        assert (temporal_resolution >= 1) and (temporal_resolution <= self.native_temporal_resolution_video), \
            f"Temporal resolution must be in [1, {self.native_temporal_resolution_video}] ms"
        self.responses, self.videos, self.T = self.change_temporal_resolution(
            self.native_temporal_resolution_video,
            self.videos,
            self.native_temporal_resolution_responses,
            self.responses,
            temporal_resolution,
        )
        self.dt = temporal_resolution  # Updated temporal resolution (ms)
            
        # Optionally normalize responses
        if normalize_responses:
            self.responses = self.normalize_responses(self.responses)
            
        # Optionally smooth responses with a gaussian kernel
        if response_smoothing:
            self.responses = self.smooth_responses(self.responses)

        # change spatial resolution of video stims
        if spatial_resol != (self.H, self.W):
          self.videos = self.change_spatial_resolution(self.videos, spatial_resol)

        # change from RGB to grayscale
        if grayscale:
            self.videos = self.from_rgb_to_grayscale(self.videos)

        # Optionally normalize videos
        if normalize_videos:
            self.videos = self.normalize_videos(self.videos)
            
        # Optionally add random noise to videos
        if add_noise:
            self.videos = self.add_noise_to_videos(self.videos)
            
        # Optionally split each clip into shorter clips.
        if split_into_clips:
            self.responses, self.videos = self.split_into_clips(
                dt=self.dt,
                clip_length_ms=new_clip_len,
            )       

        self.I = [0]   # select neuron #0 by default
        print(f"{set} set contains {len(self.videos)} videos.")
        self.signal_powers = self.get_responses_signal_power(self.responses) # (N_neurons, N_seqs)

    def __getitem__(self, video_index):
        video = self.videos[video_index]                    # (C, H, W, T)
        response = self.responses[self.I, video_index]      # (N_neurons, N_repeats, T)
        signal_power = self.signal_powers[self.I, video_index]  # (N_neurons,)
        nrn_mask = torch.ones(len(self.I)).bool()               # (N_neurons,)
        return video, response, signal_power, nrn_mask
      
    def __len__(self):
        """
        Returns the number of video samples available in the dataset.
        """
        return len(self.videos)
